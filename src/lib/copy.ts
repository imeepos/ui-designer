/**
 * Copy text to the clipboard with a legacy fallback: the Tauri webview only
 * exposes `navigator.clipboard` on secure contexts, so a hidden-textarea
 * `execCommand("copy")` path keeps desktop windows working. Returns whether
 * the copy succeeded (callers show a transient confirmation).
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fall through to the legacy path.
  }
  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand("copy");
    area.remove();
    return ok;
  } catch {
    return false;
  }
}
